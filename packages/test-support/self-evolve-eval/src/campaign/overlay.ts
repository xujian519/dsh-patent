/**
 * Campaign overlay rendering: the `--patch` overlay that turns a profile into
 * the self-evolve "evolved" arm of a P1-10 campaign run.
 *
 * The overlay mirrors `packages/bundle/self-evolve-app/cordis.patch.yml` and
 * adds a per-task `workspaceVerifier.buildCommand` (the bundle ships that key
 * commented out deliberately: without an explicit build command the held-in
 * verifier degrades to the weak path and the evolved arm would never commit).
 *
 * @module @deepseek-ai/dsh-self-evolve-eval/campaign/overlay
 */

/** Options for {@link renderEvolvedOverlay}. */
interface EvolvedOverlayOptions {
  /**
   * Shell command the held-in workspace verifier runs in the agent workspace
   * after a proposal; e.g. `<venv>/bin/python -m compileall -q .`. Absolute
   * paths are recommended because the verifier runs in the task workspace.
   */
  buildCommand: string
}

/** Escape a value as a single-quoted YAML scalar. */
function yamlScalar(value: string): string {
  return `'${value.replace(/'/g, "''")}'`
}

/**
 * Render the patch-list overlay for the evolved arm of one task run.
 *
 * @param options - the per-task build command.
 * @returns overlay YAML text, in the patch-list format `dsh --patch` consumes.
 */
export function renderEvolvedOverlay(options: EvolvedOverlayOptions): string {
  return [
    '# Campaign overlay generated by `pnpm eval:self-evolve campaign --arm evolved`.',
    '# Mirrors packages/bundle/self-evolve-app/cordis.patch.yml plus a per-task',
    '# workspaceVerifier.buildCommand; keep in sync when that bundle changes.',
    '- insert:',
    '    - id: self-evolve-basic',
    "      name: '@deepseek-ai/dsh-self-evolve-basic'",
    '      config:',
    '        defaultLevels: [L1-skill, L2-context]',
    '        minPatternOccurrences: 2',
    '        requireDualVerification: true',
    '        workspaceVerifier:',
    `          buildCommand: ${yamlScalar(options.buildCommand)}`,
    '    - id: tool-self-evolve',
    "      name: '@deepseek-ai/dsh-tool-self-evolve'",
    '',
  ].join('\n')
}
